"""Refuse text that credits an AI tool.

Reads lines of "<path>\t<text>" on standard input: the added lines of a
commit, or a commit message under a made-up path. Prints each line that
names an AI tool or its vendor, carries an AI co-author trailer or a
"generated with" footer, or holds the robot emoji, and exits 1 if there
was one. The commit-msg, pre-commit and pre-push hooks all read through
this one file, so they refuse the same things.

The names are written so that this file does not match them itself.
"""

import re
import sys

# Named anywhere, in any case.
NAMES = re.compile(r"\b(cl[a]ude|anthr[o]pic)\b", re.IGNORECASE)
# Other assistants, refused where they take credit: a co-author trailer or a
# "generated with" line. Elsewhere the words have ordinary meanings (an
# editor's cursor, a CI log line that says "generated by").
TOOLS = r"(c[o]pilot|chatg[p]t|open[a]i|gpt-?\d|gem[i]ni|cod[e]x|curs[o]r|dev[i]n|aid[e]r|ai)"
TRAILER = re.compile(r"co-authored-by:.*\b" + TOOLS + r"\b", re.IGNORECASE)
FOOTER = re.compile(r"generated (with|by)\b.*\b" + TOOLS + r"\b", re.IGNORECASE)
ROBOT = "\U0001f916"
# Agent instruction files stay local and gitignored, so .gitignore may name
# them, on a line of their own.
AGENT_FILES = re.compile(r"/?(cl[a]ude|agents)\.md", re.IGNORECASE)


def finding(path: str, text: str) -> str | None:
    """What is wrong with one line, or None."""
    if path == ".gitignore" and AGENT_FILES.fullmatch(text.strip()):
        return None
    if NAMES.search(text):
        return "names an AI tool or its vendor"
    if TRAILER.search(text):
        return "credits an AI tool as co-author"
    if FOOTER.search(text):
        return "says an AI tool generated it"
    if ROBOT in text:
        return "holds the robot emoji"
    return None


def main() -> int:
    bad = 0
    for line in sys.stdin:
        path, _, text = line.rstrip("\n").partition("\t")
        why = finding(path, text)
        if why:
            print(f"{path}: {why}: {text.strip()[:120]}", file=sys.stderr)
            bad = 1
    return bad


if __name__ == "__main__":
    sys.exit(main())
